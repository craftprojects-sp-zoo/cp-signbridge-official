#!/usr/bin/env bash
# Bramka: brak wzmianek o autorstwie AI w plikach repozytorium i w opisach commitów od 2026-10-21.
# Pliki: git grep po plikach śledzonych i nowych (poza wyjątkami).
# Commity: git log --since=2026-10-21 --format=%B — stopki współautorstwa, "Generated with", nazwy narzędzi i modeli.
# Wyjątki (funkcje produktu, dane testowe): tools/sprawdz-autorstwo.wyjatki — jedna ścieżka (pathspec git) w linii, # = komentarz.
# Kod wyjścia: 0 = czysto, 1 = są wzmianki.
set -u
cd "$(git rev-parse --show-toplevel)" || exit 2

OD="2026-10-21"
WZORZEC='co-authored-by|generated with (\[|claude|ai\b)|generated by (claude|ai\b|an? ai)|wygenerowan[a-z]* (przez|za pomoc[ąa]) (ai|sztuczn|claude|model)|claude|anthropic|🤖|\b(sonnet|opus|haiku|fable)\b'
SKRYPT="tools/sprawdz-autorstwo.sh"
WYJATKI="tools/sprawdz-autorstwo.wyjatki"

# Sam skrypt, plik wyjątków i .gitignore (lista plików lokalnych) nie są sprawdzane.
wyl=(":(exclude)$SKRYPT" ":(exclude)$WYJATKI" ":(exclude).gitignore")
if [ -f "$WYJATKI" ]; then
  while IFS= read -r l || [ -n "$l" ]; do
    l="${l%$'\r'}"
    case "$l" in ''|'#'*) continue ;; esac
    wyl+=(":(exclude)$l")
  done < "$WYJATKI"
fi

blad=0
pliki=$(git grep -I -n -i -P --untracked -e "$WZORZEC" -- . "${wyl[@]}" 2>/dev/null | cut -c1-200)
if [ -n "$pliki" ]; then
  echo "Wzmianki o autorstwie AI w plikach:"; echo "$pliki"; blad=1
fi

while IFS= read -r h; do
  [ -z "$h" ] && continue
  if git log -1 --format=%B "$h" | grep -q -i -P "$WZORZEC"; then
    echo "Wzmianka o autorstwie AI w opisie commitu: $h"; blad=1
  fi
done < <(git log --since="$OD 00:00" --format=%H 2>/dev/null)

[ "$blad" -eq 0 ] && echo "OK: brak wzmianek o autorstwie AI."
exit "$blad"
